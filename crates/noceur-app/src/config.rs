//! Settings that live outside the index.
//!
//! The index is a cache of what is on disk and is safe to delete at any time;
//! anything here is not derived from anything and would be gone with it. So far
//! that means the Discogs token and the Tidal app credentials.
//!
//! The token is stored in plain text in the user's own profile, the way every
//! tool of this kind does it. That is worth being explicit about rather than
//! implying a protection that is not there. Two things follow from it: the file
//! sits beside the executable rather than in the index, so it is not swept up by
//! "delete the cache and rescan"; and nothing ever hands the token back to the
//! front end — the UI can ask *whether* one is set, never what it is.

use serde::{Deserialize, Serialize};
use std::path::{Path, PathBuf};

#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(rename_all = "camelCase", default)]
pub struct Config {
    /// Personal access token for Discogs, generated by the user on their own
    /// account. Empty when they have not set one.
    pub discogs_token: String,
    /// Client ID and secret of the user's own Tidal developer app. Stored and
    /// guarded exactly like the Discogs token.
    #[serde(default)]
    pub tidal_client_id: String,
    #[serde(default)]
    pub tidal_client_secret: String,
    /// Whether Find metadata may ask Shazam about tracks AcoustID does not
    /// know. Off by default: it is Shazam's private app API, which can change
    /// or block without notice, and the user should choose to rely on it.
    #[serde(default)]
    pub shazam: bool,
    /// Whether a tag write puts the file's modified date back afterwards.
    ///
    /// On by default. "Date modified" is what a DJ sorts by to find what
    /// arrived last week, and retagging a folder moves every file in it to the
    /// top of that sort at once — irreversibly, since the old dates are gone.
    /// Anyone who wants the ordinary filesystem behaviour can turn it off; the
    /// reverse is not available once the dates have moved.
    #[serde(default = "yes")]
    pub preserve_dates: bool,
    /// Where the window was when it was last closed.
    ///
    /// `None` until it has been closed once, which is what makes the size in
    /// `tauri.conf.json` a first-run default rather than a permanent one.
    #[serde(default)]
    pub window: Option<crate::placement::Placement>,
    /// Buttons the user has defined.
    ///
    /// Full of one person's drive letters and installed programs, which is
    /// exactly why they live here — beside the executable, never in the
    /// repository.
    #[serde(default)]
    pub actions: Vec<crate::actions::Action>,
    /// Where ffmpeg is, for the converter: the executable or its folder.
    /// Empty to look beside Noceur and then on `PATH`.
    #[serde(default)]
    pub ffmpeg_path: String,
    /// Measuring BPM and key in the background, and what to do with the result.
    #[serde(default)]
    pub analysis: crate::background::Settings,
    /// The `rekordbox.xml` playlists are sent to. Empty to use the one
    /// rekordbox's Imported Library is set to.
    #[serde(default)]
    pub rekordbox_xml: String,
}

fn yes() -> bool {
    true
}

impl Default for Config {
    fn default() -> Config {
        Config {
            discogs_token: String::new(),
            tidal_client_id: String::new(),
            tidal_client_secret: String::new(),
            shazam: false,
            preserve_dates: true,
            window: None,
            actions: Vec::new(),
            ffmpeg_path: String::new(),
            analysis: Default::default(),
            rekordbox_xml: String::new(),
        }
    }
}

impl Config {
    /// Reads the config, falling back to defaults for anything unreadable.
    ///
    /// A corrupt or half-written file costs the settings in it, not the session:
    /// the app has to start regardless, and the worst case is a token that has
    /// to be pasted again.
    pub fn load(path: &Path) -> Config {
        std::fs::read_to_string(path)
            .ok()
            .and_then(|text| serde_json::from_str(&text).ok())
            .unwrap_or_default()
    }

    pub fn save(&self, path: &Path) -> Result<(), String> {
        let text = serde_json::to_string_pretty(self).map_err(|e| e.to_string())?;
        std::fs::write(path, text).map_err(|e| format!("cannot save settings: {e}"))
    }

    /// Where the config lives: beside the index, which is beside the executable,
    /// so a portable install stays portable.
    pub fn default_path() -> PathBuf {
        crate::state::AppState::default_db_path().with_file_name("noceur-config.json")
    }
}

/// Whether tag writes put the file's modified date back.
#[tauri::command]
pub fn preserve_dates() -> bool {
    Config::load(&Config::default_path()).preserve_dates
}

/// Turns date preservation on or off.
#[tauri::command]
pub fn set_preserve_dates(keep: bool) -> Result<bool, String> {
    let path = Config::default_path();
    let mut config = Config::load(&path);
    config.preserve_dates = keep;
    config.save(&path)?;
    Ok(config.preserve_dates)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_token_round_trips() {
        let dir = tempfile::TempDir::new().unwrap();
        let path = dir.path().join("config.json");

        Config {
            discogs_token: "abc123".into(),
            ..Default::default()
        }
        .save(&path)
        .unwrap();

        assert_eq!(Config::load(&path).discogs_token, "abc123");
    }

    /// The app has to start whatever state this file is in. A half-written or
    /// hand-edited config costs the settings in it, not the session.
    #[test]
    fn an_unreadable_config_falls_back_to_defaults() {
        let dir = tempfile::TempDir::new().unwrap();
        let missing = dir.path().join("nothing.json");
        assert_eq!(Config::load(&missing).discogs_token, "");

        let broken = dir.path().join("broken.json");
        std::fs::write(&broken, "{ not json").unwrap();
        assert_eq!(Config::load(&broken).discogs_token, "");
    }

    /// The protective default has to survive a config written before the
    /// setting existed, or an upgrade would quietly start moving dates.
    #[test]
    fn preserving_dates_is_on_unless_it_was_turned_off() {
        let dir = tempfile::TempDir::new().unwrap();
        let path = dir.path().join("config.json");

        assert!(Config::default().preserve_dates);

        std::fs::write(&path, r#"{"discogsToken":"x"}"#).unwrap();
        assert!(Config::load(&path).preserve_dates, "an older config");

        std::fs::write(&path, r#"{"preserveDates":false}"#).unwrap();
        assert!(!Config::load(&path).preserve_dates, "turned off explicitly");
    }

    /// Kept out of the index deliberately: that file is a cache and is meant to
    /// be deletable without losing anything that cannot be rebuilt.
    #[test]
    fn the_config_sits_beside_the_index_rather_than_inside_it() {
        let path = Config::default_path();
        assert_eq!(path.file_name().unwrap(), "noceur-config.json");
        assert_eq!(
            path.parent(),
            crate::state::AppState::default_db_path().parent()
        );
    }
}
